from dataclasses import dataclass, field
from typing import Optional


@dataclass
class Box:
    номер: int
    комната: str
    вес: float
    хрупкость: bool = False
    содержимое: list = field(default_factory=list)

    def добавить(
        self,
        вещь: "Вещь",
    ) -> None:
        self.содержимое.append(вещь)

    def описать(
        self,
    ) -> str:
        список = ", ".join(str(вещь) for вещь in self.содержимое)
        хруп = " (хрупкая)" if self.хрупкость else ""
        return (
            f"Коробка #{self.номер}, комната «{self.комната}»,"
            f" вес {self.вес} кг,{хрупк}{содержимое}"
        )


@dataclass
class Вещь:
    название: str
    вес: float = 1.0
    хрупкость: bool = False


def демо_коробки() -> list:
    коробка_1 = Box(
        номер=1,
        комната="Гостиная",
        вес=12.5,
        хрупкость=False,
    )
    коробка_1.содержимое = ["Книги", "Пульт", "Мяч"]

    коробка_2 = Box(
        номер=2,
        комната="Спальня",
        вес=8.0,
        хрупкость=True,
    )
    коробка_2.содержимое = ["Часы", "Зеркало", "Фотоальбом"]

    коробка_3 = Box(
        номер=3,
        комната="Кухня",
        вес=15.0,
        хрупкость=False,
    )
    коробка_3.содержимое = ["Посуда", "Банки", "Скатерть"]

    return [коробка_1, коробка_2, коробка_3]


def main() -> None:
    коробки = демо_коробки()
    print("Добро пожаловать в MovingBoxes!")
    print("Это проект о переезде: коробки, комнаты, содержимое и хрупкие вещи.")
    print()
    print("Сгенерировано коробок:", len(коробки))
    print()
    for коробка in коробки:
        print(коробка.описать())
    print()
    хрупкое = [к for к in коробки if к.хрупкость]
    print("Хрупких коробок:", len(хрупкое))


if __name__ == "__main__":
    main()
